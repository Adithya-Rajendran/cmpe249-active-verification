"""Write tests/golden/shelf_goldens.json: canonical hashes of every shelf output (tabletop wave, step 0), made at origin/main
51cf0a3 BEFORE any tabletop edit to sim/. Masking rules: tests/shelf_golden.py. Needs the share (read only).

Every golden is computed from the share's files AND reproduced by the current code before it is written (the script stops
if they disagree): the 64 shelf_v3 dev arrangements (dev60) regenerated in full, sim/episodes.py rebuilt on a JSON-only
scratch copy of shelf_dev_v3, sim/check_batch.py re-run on shelf_dev_v3 with its output in a scratch folder (~85 s).

    PYTHONPATH=. uv run --no-project --python 3.13.5 --with numpy==2.5.3 --with opencv-python-headless==5.0.0.93 \\
        python tests/golden/make_shelf_goldens.py
"""
from __future__ import annotations

import json
import platform
import subprocess
import sys
import tempfile
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))
from sim import arrange as A  # noqa: E402
from tests import shelf_golden as G  # noqa: E402

CODE_FILES = ("sim/arrange.py", "sim/rig.py", "sim/episodes.py", "sim/alignment.py", "sim/check_batch.py", "sim/isaac_batch.py",
              "sim/isaac_rig.py")


def need(cond: bool, what: str) -> None:
    if not cond:
        raise SystemExit(f"golden NOT written: {what}")


def main() -> int:
    t0 = time.time()
    commit = subprocess.run(["git", "-C", str(REPO), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    dirty = subprocess.run(["git", "-C", str(REPO), "status", "--porcelain", "--untracked-files=no", "sim", "configs"], capture_output=True, text=True).stdout
    need(not dirty.strip(), f"sim/ or configs/ has uncommitted changes:\n{dirty}")
    code = {f: G.sha256_file(REPO / f) for f in CODE_FILES}
    ctx = G.generator_context()

    # ---- generator: the 64 dev60 arrangements, the slot lists, the index files
    arrs = {}
    for p in sorted(G.DEV60.glob("*.json")):
        a = json.loads(p.read_text())
        need(A.arrangement_hash(a) == a["arrangement_sha256"], f"{p.name}: stored arrangement_sha256 does not recompute")
        need(a["provenance"]["generator"]["sha256"] == code["sim/arrange.py"] and a["provenance"]["rig_py"]["sha256"] == code["sim/rig.py"],
             f"{p.name}: generated by other code than this checkout")
        arrs[a["arrangement_id"]] = {"canonical_sha256": G.sha256_json(G.canonical_arrangement(a)),
                                     "arrangement_sha256": a["arrangement_sha256"]}
    need(len(arrs) == 64, f"{len(arrs)} dev60 arrangements, expected 64")
    log = json.loads((G.DEV60 / "index" / "generation_log.json").read_text())
    need(log["reserve_used"] == {} and log["replacements"] == [], "dev60 used reserve seeds (the subset regeneration assumes none)")
    t1 = time.time()
    regen = G.regenerate(ctx, range(60))
    regen_s = round(time.time() - t1, 1)
    for i, a in regen.items():
        need(G.sha256_json(G.canonical_arrangement(a)) == arrs[i]["canonical_sha256"], f"{i}: regeneration differs from dev60")
        need(a["arrangement_sha256"] == arrs[i]["arrangement_sha256"], f"{i}: regenerated arrangement_sha256 differs")
    slots = G.slot_list_hashes(ctx)
    need(G.sha256_json(json.loads((G.DEV60 / "index" / "slots.json").read_text())["slots"]) == slots["dev"]["sha256"],
         "dev60 slots.json differs from slot_list(dev)")
    index = {fn: G.sha256_json(G.canonical_index_file(fn, json.loads((G.DEV60 / "index" / fn).read_text())))
             for fn in ("index.json", "slots.json", "generation_log.json")}

    # ---- rendered set: episodes (rebuilt on a scratch copy), check_batch (re-run into memory)
    ep_share = G.episodes_hashes(G.SHELF_DEV_V3)
    with tempfile.TemporaryDirectory() as t:
        ep_copy = G.rebuild_episodes(G.SHELF_DEV_V3, Path(t))
    need(ep_copy == ep_share, "sim/episodes.py on a copy does not reproduce the share's outputs: "
         + json.dumps({k: [ep_copy["files"].get(k), v] for k, v in ep_share["files"].items() if ep_copy["files"].get(k) != v}))
    check_share = G.check_file_hashes(json.loads((G.SHELF_DEV_V3 / "check" / "check.json").read_text()))
    t2 = time.time()
    check_run = G.check_set_hash(G.SHELF_DEV_V3)
    check_s = round(time.time() - t2, 1)
    need(check_run == check_share["check.json"], "sim/check_batch.py does not reproduce the share's check/check.json")
    check_sub = G.check_arrangement_hashes(G.SHELF_DEV_V3, G.CHECK_SUBSET)
    need(all(check_sub[i] == check_share["arrangements"][i] for i in G.CHECK_SUBSET), "check_arrangement subset differs")

    golden = {
        "schema": "cmpe249.shelf-goldens.v1",
        "made": {"by": "tests/golden/make_shelf_goldens.py", "commit": commit, "python": platform.python_version(),
                 "date_note": "tabletop wave step 0, before any tabletop edit to sim/"},
        "canonical": "sha256 of json.dumps(obj, sort_keys=True, separators=(',', ':')) after the masks in tests/shelf_golden.py "
                     "(code-hash fields only); .md files: sha256 of the text with the set root rewritten",
        "code_hashes": code,
        "generator": {
            "config": G.CONFIG, "source": str(G.DEV60),
            "slot_list": slots,
            "arrangements": arrs,
            "index_files": index,
            "regenerated_all": {"n": len(regen), "seconds": regen_s,
                                "note": "all 60 slots + 4 design cases regenerated and equal when this file was written"},
            "test_subset": {"slots": G.REGEN_SUBSET, "design_cases": "all 4",
                            "note": "the default test regenerates these; CMPE249_GOLDEN_FULL=1 regenerates all 60 slots"},
        },
        "rendered_set": {
            "root": str(G.SHELF_DEV_V3),
            "episodes": ep_share,
            "episodes_note": "sim/episodes.py build(root, ['L1', 'same'], positions_shelf_A.json, generation_log) on a JSON-only copy "
                             "(arrangement.json + labels.json per folder) reproduces these with the copy's root rewritten",
            "check_batch": {"check.json": check_share["check.json"], "seconds": check_s,
                            "arrangements": {i: check_share["arrangements"][i] for i in sorted(check_share["arrangements"])}},
        },
    }
    with tempfile.TemporaryDirectory() as t:
        fake = G.fake_render(G.fake_input_arrangement(golden, G.FAKE_ARRANGEMENT, ctx), Path(t))
    need(fake["file_sha256"] == G.sha256_file(G.DEV60 / f"{G.FAKE_ARRANGEMENT}.json"),
         "the stub-render input is not byte-identical to the dev60 file")
    golden["fake_isaac"] = {"arrangement": G.FAKE_ARRANGEMENT, **fake}
    golden["stage_log"] = {i: G.stage_log_hash(G.fake_input_arrangement(golden, i, ctx)) for i in G.STAGE_LOG_ARRANGEMENTS}
    G.GOLDEN_PATH.write_text(json.dumps(golden, indent=1) + "\n")
    print(f"wrote {G.GOLDEN_PATH.relative_to(REPO)} in {time.time() - t0:.0f} s (regeneration {regen_s} s, check_batch {check_s} s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
